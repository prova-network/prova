/**
 * Write a complete prover.toml at `STATE_ROOT/prover.toml`. Covers every
 * section provad's config struct (prover/pkg/config/config.go) requires:
 *
 *   [identity]   keystore_path -> the file we just materialized
 *   [chain]      rpc_url + chain_id + contract addresses, from the
 *                user-selected network preset
 *   [storage]    data_dir -> the user-selected storage location
 *   [http]       disabled (desktop default; users wanting HTTPS retrieval
 *                run the headless prover instead)
 *   [metrics]    enabled on loopback for the dashboard
 *   [dashboard]  enabled on loopback (loop-only by default)
 *
 * The file is overwritten on every launch so any change made through
 * the UI reflects on the next supervisor restart.
 *
 * @param {string} keystorePath  Absolute path to the keystore.json that
 *   provad must decrypt with $PROVA_KEYSTORE_PASSPHRASE.
 */
async function ensureProverConfig (keystorePath) {
  const tomlPath = join(consts.STATE_ROOT, 'prover.toml')
  const dataDir = provaConfig.getStorageDir()
  const network = provaConfig.getNetworkConfig()
  await fs.mkdir(consts.STATE_ROOT, { recursive: true })
  await fs.mkdir(dataDir, { recursive: true })

  // TOML allows backslashes inside double-quoted strings only when
  // escaped, so use forward slashes everywhere. Works on Windows too.
  const fwd = (/** @type {string} */ p) => p.replace(/\\/g, '/')
  const safeDataDir = fwd(dataDir)
  const safeKeystore = fwd(keystorePath)

  const c = network.contracts
  const toml = [
    '# Auto-generated by Prova Desktop. Edits are overwritten on launch.',
    `# Network: ${network.label} (${network.key})`,
    '',
    '[identity]',
    `keystore_path = "${safeKeystore}"`,
    '# Passphrase is supplied via $PROVA_KEYSTORE_PASSPHRASE at runtime.',
    '',
    '[chain]',
    `rpc_url = "${network.rpcUrl}"`,
    `chain_id = ${network.chainId}`,
    'poll_interval_seconds = 12',
    '',
    '[chain.contracts]',
    `prova_token = "${c.provaToken}"`,
    `proof_verifier = "${c.proofVerifier}"`,
    `prover_registry = "${c.proverRegistry}"`,
    `prover_staking = "${c.proverStaking}"`,
    `content_registry = "${c.contentRegistry}"`,
    `storage_marketplace = "${c.storageMarketplace}"`,
    '',
    '[storage]',
    `data_dir = "${safeDataDir}"`,
    '',
    '[http]',
    'enabled = false',
    '',
    '[metrics]',
    'enabled = true',
    'listen_addr = "127.0.0.1:9095"',
    '',
    '[dashboard]',
    'enabled = false',
    'listen_addr = "127.0.0.1:9096"',
    ''
  ].join('\n')

  await fs.writeFile(tomlPath, toml, 'utf8')
  log.info(format('wrote prover.toml: network=%s data_dir=%s', network.key, safeDataDir))
}

